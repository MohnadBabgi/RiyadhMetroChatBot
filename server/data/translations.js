// Function to translate Arab text to English using patterns
function translateDynamic(text) {
    let translated = text;

    // Replace station names first
    for (const [ar, en] of Object.entries(stationReplacements)) {
        translated = translated.replace(new RegExp(ar, 'g'), en);
    }

    // Pattern 1: Where is X station?
    // أين تقع محطة X؟
    if (translated.match(/^أين تقع محطة (.+)\?$/)) {
        return translated.replace(/^أين تقع محطة (.+)\?$/, 'Where is $1 station?');
    }

    // Pattern 2: Travel time from X to Y
    // كم تستغرق الرحلة من محطة X إلى محطة Y؟
    // كم تستغرق الرحلة من محطة X إلى Y؟
    if (translated.match(/^كم تستغرق الرحلة من محطة (.+) إلى (محطة )?(.+)\?$/)) {
        return translated.replace(/^كم تستغرق الرحلة من محطة (.+) إلى (محطة )?(.+)\?$/, 'How long is the trip from $1 station to $3?');
    }

    // Pattern 3: Travel time between X and Y
    // كم الوقت بين محطة X ومحطة Y؟
    if (translated.match(/^كم الوقت بين محطة (.+) ومحطة (.+)\?$/)) {
        return translated.replace(/^كم الوقت بين محطة (.+) ومحطة (.+)\?$/, 'How long is the time between $1 station and $2 station?');
    }

    // Pattern 4: Last train from X to Y
    // ما موعد آخر قطار من محطة X إلى محطة Y؟
    if (translated.match(/^ما موعد آخر قطار من محطة (.+) إلى (محطة )?(.+)\?$/)) {
        return translated.replace(/^ما موعد آخر قطار من محطة (.+) إلى (محطة )?(.+)\?$/, 'When is the last train from $1 station to $3?');
    }

    // Pattern 5: First train from X to Y
    // متى ينطلق أول قطار من محطة X إلى (محطة )?Y؟
    if (translated.match(/^متى ينطلق أول قطار من محطة (.+) إلى (محطة )?(.+)\?$/)) {
        return translated.replace(/^متى ينطلق أول قطار من محطة (.+) إلى (محطة )?(.+)\?$/, 'When does the first train depart from $1 station to $3?');
    }

    // Pattern 6: First train from X (general)
    // متى تبدأ أول رحلة من محطة X؟
    if (translated.match(/^متى تبدأ أول رحلة من محطة (.+)\?$/)) {
        return translated.replace(/^متى تبدأ أول رحلة من محطة (.+)\?$/, 'When does the first trip start from $1 station?');
    }

    return null;
}

// Simple dynamic answer translation for duration/time
function translateDynamicAnswer(answer) {
    if (!answer) return null;
    let text = answer.trim();

    // Pattern: "حوالي X دقيقة." or "حوالي X دقيقة"
    const durationMatch = text.match(/^حوالي (\d+) دقيقة\.?$/);
    if (durationMatch) {
        return `About ${durationMatch[1]} minutes.`;
    }

    // Pattern: "حوالي X دقائق."
    const durationMatch2 = text.match(/^حوالي (\d+) دقائق\.?$/);
    if (durationMatch2) {
        return `About ${durationMatch2[1]} minutes.`;
    }

    return null;
}

export function getTranslation(arabicQuestion, arabicAnswer) {
    if (!arabicQuestion) return null;
    const cleanQuestion = arabicQuestion.trim();

    // 1. Check static map
    if (staticTranslations[cleanQuestion]) {
        return staticTranslations[cleanQuestion];
    }

    // 2. Try dynamic generation
    const dynamicQ = translateDynamic(cleanQuestion);
    if (dynamicQ) {
        const dynamicA = translateDynamicAnswer(arabicAnswer);
        return {
            question_en: dynamicQ,
            // Use dynamic answer if found, otherwise keep null (fallback to Arabic)
            answer_en: dynamicA || null
        };
    }

    return null;
}
